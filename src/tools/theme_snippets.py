"""Copy the shared pieces of the preview into the Shopify theme (../chesed-theme), so both stay in step.

    python src/tools/theme_snippets.py [theme folder]

Writes:
  assets/   chesed.css (stylesheet, font paths for Shopify), fonts, lenis.min.js, the non-product photos
  snippets/ spin.liquid, length-trio.liquid, length-table.liquid, length-table-short.liquid, length-pick-<photo>.liquid, length-pick-crochet-<photo>.liquid, length-trio-crochet.liquid, length-table-crochet.liquid, reviews.liquid, logo.liquid, chesed-config.liquid
The theme's own script (assets/chesed.js) is edited in the theme, not copied: its cart talks to Shopify.
Photos in snippets use Liquid's asset_url, so they are served from the theme.
"""
import json, os, re, shutil, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from jinja2 import Environment, FileSystemLoader, select_autoescape
from markupsafe import Markup
import data as D

SRC = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ROOT = os.path.dirname(SRC)
THEME = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(ROOT), "chesed-theme")
PHOTOS = ["length-straight", "length-wavy", "length-curly", "banner-curly-burgundy", "banner-curly-black",
          "wig-cap-one-size", "wig-cap-secure-fit", "placeholder"]

env = Environment(loader=FileSystemLoader(os.path.join(SRC, "templates")), autoescape=select_autoescape(["html"]),
                  trim_blocks=True, lstrip_blocks=True)
env.globals.update(img=lambda file, w: Markup("{{ '%s-%d.webp' | asset_url }}" % (file, w)),
                   free_ship=D.FREE_SHIP, reviews=D.REVIEWS, spin_prizes=D.SPIN_PRIZES, wheel=lambda: Markup(D.wheel_svg()),
                   spin_odds=", ".join(f'{p["label"]} {p["weight"]}%' for p in D.SPIN_PRIZES))

def write(rel, text):
    path = os.path.join(THEME, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8", newline="\n").write(text.strip() + "\n")

def macro(template, name, *args, **kw):
    return str(getattr(env.get_template(template).module, name)(*args, **kw))

head = "{%- comment -%} Generated by src/tools/theme_snippets.py in the preview repo. Edit there, not here. {%- endcomment -%}\n"

# snippets
write("snippets/spin.liquid", head + env.get_template("partials/spin.html").render(shopify=True))
write("snippets/logo.liquid", head + open(os.path.join(SRC, "templates", "partials", "logo.html"), encoding="utf-8").read())
write("snippets/length-trio.liquid", head + macro("partials/length_photos.html", "length_trio", [D.length_photo(c["key"]) for c in D.LENGTH_PHOTOS]))
write("snippets/length-table.liquid", head + macro("partials/length_photos.html", "length_table", D.LENGTHS, D.LANDMARKS, D.CURLY_LANDMARKS))
write("snippets/length-table-short.liquid", head + macro("partials/length_photos.html", "length_table", D.LENGTHS, D.LANDMARKS))   # homepage: straight only
for c in D.LENGTH_PHOTOS:   # the wig page's photo, where tapping a length picks it
    write(f"snippets/length-pick-{c['key']}.liquid", head + macro("partials/length_photos.html", "length_photo", D.length_photo(c["key"]),
                                                                  D.DEFAULT_LENGTH, True, "(max-width:720px) 92vw, 420px"))
for c in D.LENGTH_PHOTOS:   # crochet pages: 12" to 22"
    write(f"snippets/length-pick-crochet-{c['key']}.liquid", head + macro("partials/length_photos.html", "length_photo", D.length_photo(c["key"], D.CROCHET_LENGTHS),
                                                                          D.CROCHET_DEFAULT_LENGTH, True, "(max-width:720px) 92vw, 420px"))
write("snippets/length-trio-crochet.liquid", head + macro("partials/length_photos.html", "length_trio", [D.length_photo(c["key"], D.CROCHET_LENGTHS) for c in D.LENGTH_PHOTOS]))
write("snippets/length-table-crochet.liquid", head + macro("partials/length_photos.html", "length_table", D.CROCHET_LENGTHS, D.CROCHET_LANDMARKS, D.CROCHET_CURLY_LANDMARKS))
write("snippets/reviews.liquid", head + macro("partials/macros.html", "reviews_block"))
write("snippets/chesed-config.liquid", head + "<script>window.CHESED=" + json.dumps(dict(
    freeShip=D.FREE_SHIP, lens=D.LENGTHS, land=D.LANDMARKS, landc=D.CURLY_LANDMARKS,
    clens=D.CROCHET_LENGTHS, cland=D.CROCHET_LANDMARKS, clandc=D.CROCHET_CURLY_LANDMARKS, cphoto=D.CROCHET_LENGTH_PHOTO)) + ";</script>")

# assets
css = open(os.path.join(ROOT, "assets", "css", "style.css"), encoding="utf-8").read()
css = re.sub(r"url\(\.\./fonts/([^)]+)\)", r"url(\1)", css)
write("assets/chesed.css", css)
for f in os.listdir(os.path.join(ROOT, "assets", "fonts")):
    shutil.copy(os.path.join(ROOT, "assets", "fonts", f), os.path.join(THEME, "assets", f))
shutil.copy(os.path.join(ROOT, "assets", "js", "vendor", "lenis.min.js"), os.path.join(THEME, "assets", "lenis.min.js"))
for name in PHOTOS:
    for w in (560, 1024):
        shutil.copy(os.path.join(ROOT, "assets", "p", f"{name}-{w}.webp"), os.path.join(THEME, "assets", f"{name}-{w}.webp"))
print(f"Theme pieces written to {THEME}")
